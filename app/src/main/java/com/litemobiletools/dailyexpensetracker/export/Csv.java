package com.litemobiletools.dailyexpensetracker.export;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import java.io.IOException;
import java.io.Writer;

/**
 * RFC 4180 CSV helpers. Rows end with CRLF; a field is quoted when it contains a comma, a double
 * quote, CR or LF, and embedded quotes are doubled.
 *
 * <p>User-entered text (notes, category and payment-method names) can start with characters that
 * spreadsheet apps treat as a formula ({@code = + - @}, tab, CR). Such text fields are prefixed with
 * an apostrophe so they open as plain text. Numeric columns are produced by the app itself and are
 * written unchanged, so negative amounts stay numbers.
 */
public final class Csv {

    public static final String CRLF = "\r\n";
    /** Written first so spreadsheet apps detect UTF-8. */
    public static final char BOM = (char) 0xFEFF;

    private Csv() {
    }

    /** A user-supplied text field: formula-neutralised, then quoted if needed. Null becomes empty. */
    @NonNull
    public static String text(@Nullable String raw) {
        if (raw == null || raw.isEmpty()) {
            return "";
        }
        String value = startsLikeFormula(raw) ? "'" + raw : raw;
        return quoteIfNeeded(value);
    }

    /** A value generated by the app (numbers, dates, codes). Quoted only if it needs it. */
    @NonNull
    public static String plain(@Nullable String raw) {
        return raw == null ? "" : quoteIfNeeded(raw);
    }

    static boolean startsLikeFormula(@NonNull String value) {
        char first = value.charAt(0);
        return first == '=' || first == '+' || first == '-' || first == '@' || first == '\t' || first == '\r'
                || first == (char) 0xFF1D || first == (char) 0xFF0B || first == (char) 0xFF0D || first == (char) 0xFF20;
    }

    @NonNull
    static String quoteIfNeeded(@NonNull String value) {
        boolean needs = false;
        for (int i = 0; i < value.length() && !needs; i++) {
            char c = value.charAt(i);
            needs = c == ',' || c == '"' || c == '\n' || c == '\r';
        }
        if (!needs) {
            return value;
        }
        return '"' + value.replace("\"", "\"\"") + '"';
    }

    /** Writes already-escaped fields as one row. */
    public static void row(@NonNull Writer writer, @NonNull String... escapedFields) throws IOException {
        for (int i = 0; i < escapedFields.length; i++) {
            if (i > 0) {
                writer.write(',');
            }
            writer.write(escapedFields[i]);
        }
        writer.write(CRLF);
    }

    /** Writes a header row (names are fixed ASCII identifiers). */
    public static void header(@NonNull Writer writer, @NonNull String[] names) throws IOException {
        row(writer, names);
    }
}
